# shellcheck shell=bash
# The rename log of the database data folders, and the check before a database starts.
# A rename of a whole data folder is one mv, but a power cut between the mv and the record of it
# would leave a folder that an image of the next major then fills with an empty cluster. So:
#   1  the intent is written to state.json first (dir_op.id/from/to/phase=intent), saved
#   2  the mv
#   3  dir_op.phase=done, saved
# A reader of state.json that finds phase=intent looks at both ends (cx_dirop_recover): from there
# and to not = the mv was not made, make it; from not there and to there = made, record it; any
# other combination is not guessed: nothing starts and both paths are shown (CX_DIROP_AMBIGUOUS).
# Every entry that starts the bundled database calls cx_dirop_start_check first.
# Needs lib/state.sh, lib/pgmajor.sh and the messages loaded.
# shellcheck disable=SC2034
CX_DIROP_FROM="" CX_DIROP_TO="" CX_DIROP_WHY=""

# cx_dirop_mv <from> <to>: the one mv of a data folder (a seam for the tests).
cx_dirop_mv() { mv -- "$1" "$2"; }

# cx_dirop_save: state.json written now.
cx_dirop_save() { cx_state_save "$CX_ROOT/state.json"; }

# cx_dirop_pending: succeed when state.json holds an intent that is not completed.
cx_dirop_pending() { [ "$(cx_state_get dir_op.phase)" = intent ]; }

# cx_dirop_done_mark: phase=done.
cx_dirop_done_mark() {
  cx_state_set dir_op.phase "done"
  cx_dirop_save || return 1
  cx_log DIROP "done $(cx_state_get dir_op.from) -> $(cx_state_get dir_op.to)"
}

# cx_dirop_rename <id> <from> <to>: the three steps. 0 renamed and recorded; 1 the intent could not
# be recorded (nothing was moved); 2 the mv failed (the intent stays: cx_dirop_recover redoes it);
# 3 the folder moved but the completion could not be recorded (cx_dirop_recover completes it).
# <to> is fixed here and never regenerated by a later resume.
cx_dirop_rename() {
  local id=$1 from=$2 to=$3
  cx_dirop_pending && return 2
  cx_state_set dir_op.id "$id" && cx_state_set dir_op.from "$from" && cx_state_set dir_op.to "$to" \
    && cx_state_set dir_op.phase intent || return 1
  if ! cx_dirop_save; then
    cx_state_set dir_op.phase "done"
    return 1
  fi
  cx_log DIROP "intent $id $from -> $to"
  cx_dirop_mv "$from" "$to" || return 2
  cx_dirop_done_mark || return 3
}

# cx_dirop_recover: settle an intent left by an interruption. 0 nothing pending or settled; 1 the
# mv failed again or the completion could not be saved; 3 ambiguous (CX_DIROP_FROM/TO set, the
# caller prints cx_dirop_ambiguous_screen and stops).
cx_dirop_recover() {
  local from to
  cx_dirop_pending || return 0
  from=$(cx_state_get dir_op.from) to=$(cx_state_get dir_op.to)
  CX_DIROP_FROM=$from CX_DIROP_TO=$to
  if [ -e "$from" ] && [ ! -e "$to" ]; then
    cx_dirop_mv "$from" "$to" || return 1
    cx_dirop_done_mark || return 1
  elif [ ! -e "$from" ] && [ -e "$to" ]; then
    cx_dirop_done_mark || return 1
  else
    return 3
  fi
}

# cx_dirop_version_of <path>: "16", "18" or "missing" for the PG_VERSION found by looking in the
# folder itself and in the one level below that holds a <major>/docker layout.
cx_dirop_version_of() {
  local f v
  for f in "$1/PG_VERSION" "$1"/*/docker/PG_VERSION; do
    [ -r "$f" ] || continue
    v=$(head -n 1 "$f" 2>/dev/null)
    [[ $v =~ ^[0-9]+$ ]] && { printf '%s' "$v"; return 0; }
  done
  printf 'missing'
}

# cx_dirop_restore_cmd: the restore of the backup taken before the upgrade, as a command.
cx_dirop_restore_cmd() {
  local b
  b=$(cx_state_get last_upgrade.backup)
  case $b in "") b=$(cx_msg dirop_backup_file) ;; /*) ;; *) b=$CX_ROOT/$b ;; esac
  printf 'sudo %s/custodexa.sh restore %s%s' "$CX_ROOT" "$b" "$(cx_status_lang_arg)"
}

# cx_dirop_du <path>: the size of a folder in bytes.
cx_dirop_du() {
  local k
  k=$(du -sk -- "$1" 2>/dev/null | cut -f1)
  printf '%s' $((${k:-0} * 1024))
}

# cx_dirop_dir_lines <path>: the folder, and under it the version it holds and its size, or that it
# is not there.
cx_dirop_dir_lines() {
  local v
  printf '%s\n' "$(cx_msg dirop_dir_row "$1")"
  if [ -e "$1" ]; then
    v=$(cx_dirop_version_of "$1")
    [ "$v" != missing ] || v=$(cx_msg dirop_ver_none)
    printf '%s\n' "$(cx_msg dirop_dir_ver "$v" "$(cx_size_human "$(cx_dirop_du "$1")")")"
  else
    printf '%s\n' "$(cx_msg dirop_dir_gone)"
  fi
}

# cx_dirop_ambiguous_screen: the screen when the rename cannot be told apart: both folders are
# there, or neither is.
cx_dirop_ambiguous_screen() {
  local f=$CX_DIROP_FROM t=$CX_DIROP_TO id key
  id=$(cx_state_get dir_op.id)
  case $id in
    rolled-back) key=rolled_back ;;
    revert | before-convert | failed-convert | removing) key=${id//-/_} ;;
    *) key=other ;;
  esac
  if [ -e "$f" ] || [ -e "$t" ]; then
    cx_line FAIL "$(cx_msg dirop_ambiguous_title)"
  else
    cx_line FAIL "$(cx_msg dirop_lost_title)"
  fi
  printf '%s\n' "$(cx_msg "dirop_op_$key" "$f" "$t")"
  if [ -e "$f" ] || [ -e "$t" ]; then
    printf '%s\n' "$(cx_msg dirop_both_head)"
  else
    printf '%s\n' "$(cx_msg dirop_none_head)"
  fi
  cx_dirop_dir_lines "$f"
  cx_dirop_dir_lines "$t"
  if [ -e "$f" ] || [ -e "$t" ]; then
    printf '%s\n' "$(cx_msg dirop_ambiguous_body "$(cx_dirop_restore_cmd)")"
  else
    printf '%s\n' "$(cx_msg dirop_lost_body "$(cx_dirop_restore_cmd)")"
  fi
}

# cx_dirop_start_check <data path> <data dir> <pgdata> <major> [init]: before any start of the
# bundled database. 0 may start; 4 refuses (CX_DIROP_WHY says why: intent, ambiguous, version,
# missing, empty); an unfinished intent is settled first. A deployment with no recorded version and
# no data folder is a new install and passes. With init (the two controlled initialisations: the
# conversion's init phase, the restore's cluster creation) an absent or empty target passes
# as long as nothing is pending; a target that holds something is not accepted for init.
cx_dirop_start_check() {
  local data=$1 dir=$2 pgdata=$3 major=$4 init=${5:-} d rc=0 found
  d=$data/$dir${pgdata:+/$pgdata}
  CX_DIROP_WHY=""
  if cx_dirop_pending; then
    cx_dirop_recover || rc=$?
    if [ "$rc" = 3 ]; then CX_DIROP_WHY=ambiguous; return 4; fi
    if [ "$rc" != 0 ]; then CX_DIROP_WHY=intent; return 4; fi
  fi
  if [ "$init" = init ]; then
    if [ -d "$d" ] && [ -n "$(ls -A "$d" 2>/dev/null)" ]; then CX_DIROP_WHY=notempty; return 4; fi
    return 0
  fi
  if [ ! -e "$d/PG_VERSION" ]; then
    if [ -z "$(cx_state_get current.version)" ] && [ ! -e "$data/$dir" ]; then return 0; fi
    CX_DIROP_WHY=missing
    return 4
  fi
  found=$(cx_pgm_dir_major "$data" "$dir" "$pgdata") || { CX_DIROP_WHY=missing; return 4; }
  [ "$found" = "$major" ] || { CX_DIROP_WHY="version $found"; return 4; }
  return 0
}

# cx_dirop_guard <data path> <data dir> <pgdata> <major>: cx_dirop_start_check with its screen.
# 0 may start; otherwise the screen is printed and the code is the refusal (CX_EXIT_FAILED).
cx_dirop_guard() {
  cx_dirop_start_check "$@" && return 0
  case $CX_DIROP_WHY in
    ambiguous) cx_dirop_ambiguous_screen ;;
    intent) cx_line FAIL "$(cx_msg dirop_intent_failed "$(cx_state_get dir_op.from)" "$(cx_state_get dir_op.to)")" ;;
    missing)
      cx_line FAIL "$(cx_msg dirop_no_version)"
      printf '%s\n' "$(cx_msg dirop_missing_body "$1/$2${3:+/$3}" "$4" "$1/$2" "$(cx_dirop_restore_cmd)" "$CX_ROOT" \
        "$(cx_status_lang_arg)")"
      ;;
    notempty) cx_line FAIL "$(cx_msg dirop_not_empty "$1/$2${3:+/$3}")" ;;
    *) cx_line FAIL "$(cx_msg dirop_wrong_version "$1/$2${3:+/$3}" "${CX_DIROP_WHY#version }" "$4")" ;;
  esac
  return "$CX_EXIT_FAILED"
}

# cx_dirop_start_guard <release dir>: the entry-point form of cx_dirop_guard for the release about to
# be started. Nothing to check for an external database or a release without a MANIFEST. A release
# whose MANIFEST cannot be read is refused by the callers' own checks, not here.
cx_dirop_start_guard() {
  local rel=$1 info major dir pgdata
  [[ " ${CX_OVERLAYS:-} " != *" external-database "* ]] || return 0
  [ -f "$rel/MANIFEST.json" ] || return 0
  info=$(cx_manifest_load "$rel/MANIFEST.json" >/dev/null 2>&1 && cx_pgm_release_db \
    && printf '%s|%s|%s' "$CX_PGM_MAJOR" "$CX_PGM_DATA_DIR" "$CX_PGM_PGDATA") || return 0
  IFS='|' read -r major dir pgdata <<<"$info"
  [ -n "${CX_BK_DATA:-}" ] || cx_bk_vars >/dev/null 2>&1 || true
  [ -n "${CX_BK_DATA:-}" ] || return 0
  cx_dirop_guard "$CX_BK_DATA" "$dir" "$pgdata" "$major"
}
